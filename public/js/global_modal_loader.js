/*
 * GLOBAL MODAL LOADER - VERIFIED ROOT FIX
 * Handles Add/Edit modal buttons across core app and modules even when older
 * page scripts fail, duplicate handlers exist, or modal containers are missing.
 */
(function (window, document) {
    'use strict';

    function closest(el, selector) {
        while (el && el !== document) {
            if (el.matches && el.matches(selector)) {
                return el;
            }
            el = el.parentNode;
        }
        return null;
    }

    function normalizeContainer(selector) {
        selector = selector || '.view_modal';
        selector = String(selector).trim();
        if (!selector) {
            selector = '.view_modal';
        }
        if (selector !== 'body' && selector.charAt(0) !== '.' && selector.charAt(0) !== '#') {
            selector = '.' + selector;
        }
        return selector;
    }

    function ensureContainer(selector) {
        selector = normalizeContainer(selector);
        var container = document.querySelector(selector);
        if (container) {
            return window.jQuery ? window.jQuery(container) : null;
        }

        var div = document.createElement('div');
        div.className = 'modal fade';
        div.setAttribute('tabindex', '-1');
        div.setAttribute('role', 'dialog');
        div.setAttribute('aria-labelledby', 'gridSystemModalLabel');

        if (selector.charAt(0) === '.') {
            div.className += ' ' + selector.substring(1).replace(/[^A-Za-z0-9_-]/g, '');
        } else if (selector.charAt(0) === '#') {
            div.id = selector.substring(1).replace(/[^A-Za-z0-9_-]/g, '');
        } else {
            div.className += ' view_modal';
        }

        document.body.appendChild(div);
        return window.jQuery ? window.jQuery(div) : null;
    }

    function initModalControls($modal) {
        try {
            if (window.jQuery && window.jQuery.fn.select2) {
                $modal.find('select.select2, .select2').each(function () {
                    var $el = window.jQuery(this);
                    if ($el.is('select')) {
                        try { if ($el.data('select2')) { $el.select2('destroy'); } } catch (ignore) {}
                        $el.select2({ dropdownParent: $modal });
                    }
                });
            }
        } catch (ignore) {}

        try {
            if (window.jQuery && window.jQuery.fn.datepicker) {
                $modal.find('.datepicker').datepicker({ autoclose: true });
            }
        } catch (ignore) {}

        try {
            if (window.jQuery && window.jQuery.fn.datetimepicker) {
                $modal.find('.datetimepicker, .date_time_picker').datetimepicker();
            }
        } catch (ignore) {}
    }

    function tenantSafeInternalUrl(rawUrl) {
        if (window.erpTenantSafeUrl) { return window.erpTenantSafeUrl(rawUrl); }
        if (!rawUrl || rawUrl === '#') { return rawUrl; }

        try {
            var parsed = new URL(rawUrl, window.location.href);
            var current = new URL(window.location.href);
            var currentHost = String(current.hostname || '').toLowerCase();
            var targetHost = String(parsed.hostname || '').toLowerCase();

            // Modal links generated by Laravel action()/route() may fall back to
            // APP_URL (the central host). Internal ERP modal requests must remain
            // on the tenant host that rendered the current page.
            var sameNivasaFamily = currentHost === 'nivasa.shop' ||
                currentHost.endsWith('.nivasa.shop');
            var targetNivasaFamily = targetHost === 'nivasa.shop' ||
                targetHost.endsWith('.nivasa.shop');

            if (sameNivasaFamily && targetNivasaFamily && targetHost !== currentHost) {
                parsed.protocol = current.protocol;
                parsed.host = current.host;
                return parsed.pathname + parsed.search + parsed.hash;
            }

            // Keep same-origin ERP requests relative. This avoids future URL-root
            // changes from moving Add/Edit AJAX calls to another host.
            if (parsed.origin === current.origin) {
                return parsed.pathname + parsed.search + parsed.hash;
            }

            return parsed.href;
        } catch (ignore) {
            return rawUrl;
        }
    }

    function showError(message) {
        if (window.toastr) {
            window.toastr.error(message);
        } else {
            alert(message);
        }
    }

    function openAjaxModal(button, event) {
        if (!window.jQuery) {
            return false;
        }

        var $btn = window.jQuery(button);
        var url = tenantSafeInternalUrl($btn.data('href') || button.getAttribute('href'));

        if (!url || url === '#') {
            return false;
        }

        // Static bootstrap modals should remain untouched.
        if (!($btn.data('href')) && $btn.attr('data-toggle') === 'modal' && $btn.attr('data-target')) {
            return false;
        }

        if (event) {
            event.preventDefault();
            event.stopPropagation();
            if (event.stopImmediatePropagation) {
                event.stopImmediatePropagation();
            }
        }

        if ($btn.data('global-modal-loading')) {
            return true;
        }
        $btn.data('global-modal-loading', true);

        var containerSelector = $btn.data('container') || '.view_modal';
        var $modal = ensureContainer(containerSelector);
        if (!$modal || !$modal.length) {
            $btn.data('global-modal-loading', false);
            showError('Unable to open the form. Modal container not found.');
            return true;
        }

        $modal.html('<div class="modal-dialog" role="document"><div class="modal-content"><div class="modal-body text-center" style="padding:30px;"><i class="fa fa-spinner fa-spin"></i> Loading...</div></div></div>');
        try { $modal.modal('show'); } catch (ignore) {}

        window.jQuery.ajax({
            url: url,
            type: 'GET',
            dataType: 'html',
            cache: false,
            headers: { 'X-Requested-With': 'XMLHttpRequest' },
            success: function (html) {
                var text = String(html || '').toLowerCase();
                if (text.indexOf('<html') !== -1 || text.indexOf('<!doctype') !== -1) {
                    window.location.href = url;
                    return;
                }
                $modal.html(html);
                try { $modal.modal('show'); } catch (ignore) {}
                initModalControls($modal);
            },
            error: function (xhr) {
                try { $modal.modal('hide'); } catch (ignore) {}
                var msg = 'Unable to open the form. Please try again.';
                if (xhr && xhr.responseJSON && xhr.responseJSON.msg) {
                    msg = xhr.responseJSON.msg;
                } else if (xhr && xhr.status) {
                    msg = 'Unable to open the form. Server returned error ' + xhr.status + '.';
                }
                showError(msg);
            },
            complete: function () {
                $btn.data('global-modal-loading', false);
            }
        });

        return true;
    }

    function ensureCommonContainers() {
        if (!document.body) { return; }
        ['.view_modal', '.view_modal_2', '.fuel_tank_modal', '.expense_category_modal', '.contact_modal', '.prefix_modal', '.settlement_modal', '.add_payment'].forEach(function (selector) {
            ensureContainer(selector);
        });
    }

    document.addEventListener('DOMContentLoaded', ensureCommonContainers);

    // Capture phase: runs before older module handlers that may stop propagation.
    document.addEventListener('click', function (event) {
        var button = closest(event.target, '.btn-modal, .vat-btn-modal, .btn-vat-modal');
        if (!button) { return; }
        openAjaxModal(button, event);
    }, true);

    // Also expose for inline/manual usage if any page needs it.
    window.erpOpenAjaxModal = openAjaxModal;
})(window, document);
