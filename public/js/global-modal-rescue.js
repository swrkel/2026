/*
 * ERP Global Modal Rescue Handler
 * Fixes Add/Edit buttons that use data-href + data-container but are not
 * reached by the normal module scripts.  Loaded early from layouts/partials/javascripts.blade.php.
 */
(function () {
    'use strict';

    function closestModalButton(target) {
        if (!target) { return null; }
        if (target.closest) {
            return target.closest('.btn-modal, .vat-btn-modal, .btn-vat-modal');
        }
        while (target && target !== document) {
            if (target.classList && (
                target.classList.contains('btn-modal') ||
                target.classList.contains('vat-btn-modal') ||
                target.classList.contains('btn-vat-modal')
            )) {
                return target;
            }
            target = target.parentNode;
        }
        return null;
    }

    function getAttr(el, name) {
        return el ? (el.getAttribute(name) || '') : '';
    }

    function ensureModalContainer(selector) {
        selector = selector || '.view_modal';
        selector = String(selector).trim();
        if (!selector) { selector = '.view_modal'; }
        if (selector !== 'body' && selector.charAt(0) !== '.' && selector.charAt(0) !== '#') {
            selector = '.' + selector;
        }

        var container = document.querySelector(selector);
        if (!container && (selector.charAt(0) === '.' || selector.charAt(0) === '#')) {
            container = document.createElement('div');
            container.className = 'modal fade ' + selector.replace(/^\./, '').replace(/^#/, '');
            container.setAttribute('tabindex', '-1');
            container.setAttribute('role', 'dialog');
            container.setAttribute('aria-labelledby', 'gridSystemModalLabel');
            document.body.appendChild(container);
        }
        return container;
    }

    function initModalContent($container) {
        try {
            if (window.__currency_convert_recursively) {
                window.__currency_convert_recursively($container);
            }
        } catch (e) {}

        try {
            if (window.jQuery && jQuery.fn.select2) {
                $container.find('select.select2, .select2').each(function () {
                    var $el = jQuery(this);
                    if ($el.data('select2')) { return; }
                    $el.select2({ dropdownParent: $container });
                });
            }
        } catch (e) {}

        try {
            if (window.jQuery && jQuery.fn.datepicker) {
                $container.find('.datepicker').datepicker({
                    autoclose: true,
                    format: window.datepicker_date_format || 'mm/dd/yyyy'
                });
            }
        } catch (e) {}
    }

    function tenantSafeInternalUrl(rawUrl) {
        if (window.erpTenantSafeUrl) { return window.erpTenantSafeUrl(rawUrl); }
        if (!rawUrl || rawUrl === '#') { return rawUrl; }

        try {
            var parsed = new URL(rawUrl, window.location.href);
            var current = new URL(window.location.href);
            var currentHost = String(current.hostname || '').toLowerCase();
            var targetHost = String(parsed.hostname || '').toLowerCase();

            // Modal links generated by Laravel action()/route() may fall back to
            // APP_URL (the central host). Internal ERP modal requests must remain
            // on the tenant host that rendered the current page.
            var sameNivasaFamily = currentHost === 'nivasa.shop' ||
                currentHost.endsWith('.nivasa.shop');
            var targetNivasaFamily = targetHost === 'nivasa.shop' ||
                targetHost.endsWith('.nivasa.shop');

            if (sameNivasaFamily && targetNivasaFamily && targetHost !== currentHost) {
                parsed.protocol = current.protocol;
                parsed.host = current.host;
                return parsed.pathname + parsed.search + parsed.hash;
            }

            // Keep same-origin ERP requests relative. This avoids future URL-root
            // changes from moving Add/Edit AJAX calls to another host.
            if (parsed.origin === current.origin) {
                return parsed.pathname + parsed.search + parsed.hash;
            }

            return parsed.href;
        } catch (ignore) {
            return rawUrl;
        }
    }

    function showError(message) {
        if (window.toastr && toastr.error) {
            toastr.error(message);
        } else {
            alert(message);
        }
    }

    function openRemoteModal(button, event) {
        var href = tenantSafeInternalUrl(getAttr(button, 'data-href') || getAttr(button, 'href'));
        if (!href || href === '#') {
            return;
        }

        if (event) {
            event.preventDefault();
            event.stopPropagation();
            if (event.stopImmediatePropagation) {
                event.stopImmediatePropagation();
            }
        }

        if (button.getAttribute('data-erp-modal-loading') === '1') {
            return false;
        }
        button.setAttribute('data-erp-modal-loading', '1');

        var selector = getAttr(button, 'data-container') || '.view_modal';
        var container = ensureModalContainer(selector);
        if (!container) {
            button.removeAttribute('data-erp-modal-loading');
            window.location.href = href;
            return false;
        }

        // If jQuery/bootstrap is not available for any reason, open the form as a page
        // instead of doing nothing.
        if (!window.jQuery || !jQuery.ajax || !jQuery.fn.modal) {
            window.location.href = href;
            return false;
        }

        var $container = jQuery(container);
        $container.html('<div class="modal-dialog" role="document"><div class="modal-content"><div class="modal-body text-center" style="padding:30px;"><i class="fa fa-spinner fa-spin"></i> Loading...</div></div></div>');
        $container.modal('show');

        jQuery.ajax({
            url: href,
            type: 'GET',
            dataType: 'html',
            cache: false,
            success: function (html) {
                button.removeAttribute('data-erp-modal-loading');
                $container.html(html).modal('show');
                initModalContent($container);
            },
            error: function (xhr) {
                button.removeAttribute('data-erp-modal-loading');
                $container.modal('hide');
                var message = 'Unable to open the form.';
                if (xhr && xhr.status) {
                    message += ' Server returned ' + xhr.status + '.';
                }
                showError(message);
            }
        });

        return false;
    }

    // Capture phase is important: some pages bind other click handlers that stop
    // propagation before the old global delegated handler can see the click.
    document.addEventListener('click', function (event) {
        var button = closestModalButton(event.target);
        if (!button) { return; }
        openRemoteModal(button, event);
        return false;
    }, true);

    window.erpOpenRemoteModal = openRemoteModal;
})();
