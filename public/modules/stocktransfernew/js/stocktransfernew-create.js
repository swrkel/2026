(function (window, document) {
    'use strict';

    var config = window.StockTransferNewCreate || {};
    var body = document.querySelector('#stn-lines tbody');
    var addButton = document.getElementById('stn-add-line');
    var fromLocation = document.getElementById('stn-from-location');
    var toLocation = document.getElementById('stn-to-location');
    var fromStore = document.getElementById('stn-from-store');
    var toStore = document.getElementById('stn-to-store');
    var nextIndex = 1;

    function getJson(url) {
        return fetch(url, {
            credentials: 'same-origin',
            headers: {
                'Accept': 'application/json',
                'X-Requested-With': 'XMLHttpRequest'
            }
        }).then(function (response) {
            if (!response.ok) {
                throw new Error('Lookup request failed.');
            }
            return response.json();
        });
    }

    function refreshEnhancedSelect(select) {
        if (window.jQuery) {
            var $select = window.jQuery(select);
            $select.prop('disabled', !!select.disabled);
            // If a system/global Select2 wrapper is already attached, force it
            // to re-read the updated options and disabled state.
            if ($select.data('select2')) {
                $select.trigger('change.select2');
            }
        }
    }

    function setOptions(select, items, placeholder, selectedValue) {
        var html = '<option value="">' + placeholder + '</option>';

        (items || []).forEach(function (item) {
            var selected = String(selectedValue || '') === String(item.id)
                ? ' selected'
                : '';

            html += '<option value="' + item.id + '"' + selected + '>' +
                escapeHtml(item.text) + '</option>';
        });

        select.innerHTML = html;
        select.disabled = false;
        select.dataset.loadedLocationId = select.dataset.pendingLocationId || '';
        refreshEnhancedSelect(select);
    }

    function escapeHtml(value) {
        var element = document.createElement('div');
        element.textContent = value == null ? '' : String(value);
        return element.innerHTML;
    }

    function loadLocations() {
        return getJson(config.locationsUrl)
            .then(function (payload) {
                setOptions(
                    fromLocation,
                    payload.results,
                    'Please select',
                    config.oldFromLocation
                );
                setOptions(
                    toLocation,
                    payload.results,
                    'Please select',
                    config.oldToLocation
                );

                if (config.oldFromLocation) {
                    loadStores(
                        fromStore,
                        config.oldFromLocation,
                        config.oldFromStore
                    );
                }

                if (config.oldToLocation) {
                    loadStores(
                        toStore,
                        config.oldToLocation,
                        config.oldToStore
                    );
                }
            })
            .catch(function () {
                fromLocation.innerHTML =
                    '<option value="">Unable to load locations</option>';
                toLocation.innerHTML =
                    '<option value="">Unable to load locations</option>';
            });
    }

    function loadStores(select, locationId, selectedValue) {
        locationId = String(locationId || '').trim();

        if (!locationId) {
            select.dataset.pendingLocationId = '';
            select.dataset.loadedLocationId = '';
            select.disabled = true;
            select.innerHTML =
                '<option value="">Select location first</option>';
            refreshEnhancedSelect(select);
            return;
        }

        // Ignore duplicate events generated by a native select + Select2 for
        // the same already-loaded location, but still permit an old selected
        // value to be restored after validation.
        if (!selectedValue &&
            select.dataset.loadedLocationId === locationId &&
            !select.disabled) {
            return;
        }

        select.dataset.pendingLocationId = locationId;
        var requestToken = String(Date.now()) + ':' + Math.random();
        select.dataset.storeRequestToken = requestToken;
        select.disabled = true;
        select.innerHTML = '<option value="">Loading stores...</option>';
        refreshEnhancedSelect(select);

        getJson(
            config.storesUrl +
            '?location_id=' +
            encodeURIComponent(locationId)
        )
            .then(function (payload) {
                // A fast location change can leave an older request finishing
                // last. Never put stores from the previous location back into
                // the dropdown.
                if (select.dataset.storeRequestToken !== requestToken ||
                    select.dataset.pendingLocationId !== locationId) {
                    return;
                }

                var items = payload && Array.isArray(payload.results)
                    ? payload.results
                    : [];

                setOptions(
                    select,
                    items,
                    items.length ? 'Please select' : 'No stores for selected location',
                    selectedValue
                );
            })
            .catch(function () {
                if (select.dataset.storeRequestToken !== requestToken) {
                    return;
                }
                select.disabled = true;
                select.innerHTML =
                    '<option value="">Unable to load stores</option>';
                refreshEnhancedSelect(select);
            });
    }

    function initialiseProduct(select) {
        if (!select || select.dataset.initialised === '1') {
            return;
        }

        select.dataset.initialised = '1';

        if (window.jQuery &&
            window.jQuery.fn &&
            window.jQuery.fn.select2) {
            window.jQuery(select).select2({
                width: '100%',
                placeholder: select.dataset.placeholder || 'Search product',
                allowClear: true,
                minimumInputLength: 2,
                ajax: {
                    url: config.productLookupUrl,
                    dataType: 'json',
                    delay: 200,
                    cache: true,
                    data: function (params) {
                        return {q: params.term || ''};
                    },
                    processResults: function (data) {
                        return data && data.results
                            ? data
                            : {results: []};
                    }
                }
            });
        }
    }

    function initialiseProducts(scope) {
        (scope || document)
            .querySelectorAll('.stn-product-select')
            .forEach(initialiseProduct);
    }

    function renumberRows() {
        body.querySelectorAll('.stn-line-row')
            .forEach(function (row, index) {
                row.querySelector('.stn-row-number').textContent = index + 1;
            });
    }

    function createRow(index) {
        var row = document.createElement('tr');
        row.className = 'stn-line-row';
        row.innerHTML =
            '<td class="stn-row-number"></td>' +
            '<td><select name="lines[' + index + '][product_id]" ' +
            'class="form-control stn-product-select" ' +
            'data-placeholder="Type product name or SKU">' +
            '<option value=""></option></select></td>' +
            '<td><input name="lines[' + index + '][qty_requested]" ' +
            'class="form-control stn-number-input" type="number" ' +
            'min="0" step="0.0001" placeholder="0.0000"></td>' +
            '<td><input name="lines[' + index + '][unit_cost]" ' +
            'class="form-control stn-number-input" type="number" ' +
            'min="0" step="0.0001" placeholder="0.0000"></td>' +
            '<td><input name="lines[' + index + '][remarks]" ' +
            'class="form-control" placeholder="Optional remarks"></td>' +
            '<td class="stn-action-cell"><button type="button" ' +
            'class="stn-remove-line" title="Remove row">' +
            '<i class="fa fa-trash"></i></button></td>';

        return row;
    }

    function storeForLocationSelect(locationSelect) {
        if (!locationSelect) {
            return null;
        }
        if (locationSelect.id === 'stn-from-location') {
            return fromStore;
        }
        if (locationSelect.id === 'stn-to-location') {
            return toStore;
        }
        return null;
    }

    function reloadStoresForLocation(locationSelect) {
        var storeSelect = storeForLocationSelect(locationSelect);
        if (storeSelect) {
            loadStores(storeSelect, locationSelect.value, null);
        }
    }

    function bindLocationStoreLookup() {
        // Delegated handlers survive Select2/global form initialisers which may
        // rebind or replace handlers on the individual location controls.
        document.addEventListener('change', function (event) {
            if (event.target === fromLocation || event.target === toLocation) {
                reloadStoresForLocation(event.target);
            }
        }, true);

        if (window.jQuery) {
            window.jQuery(document)
                .off('.stnStoreLookup', '#stn-from-location, #stn-to-location')
                .on(
                    'change.stnStoreLookup select2:select.stnStoreLookup select2:clear.stnStoreLookup',
                    '#stn-from-location, #stn-to-location',
                    function () {
                        reloadStoresForLocation(this);
                    }
                );
        }
    }

    function synchroniseVisibleLocationValues() {
        if (fromLocation && fromLocation.value) {
            reloadStoresForLocation(fromLocation);
        }
        if (toLocation && toLocation.value) {
            reloadStoresForLocation(toLocation);
        }
    }

    bindLocationStoreLookup();

    addButton.addEventListener('click', function () {
        var row = createRow(nextIndex++);
        body.appendChild(row);
        renumberRows();
        initialiseProducts(row);
    });

    body.addEventListener('click', function (event) {
        var button = event.target.closest('.stn-remove-line');
        if (!button) {
            return;
        }

        var rows = body.querySelectorAll('.stn-line-row');

        if (rows.length === 1) {
            rows[0].querySelectorAll('input').forEach(function (input) {
                input.value = '';
            });

            var onlySelect = rows[0].querySelector('.stn-product-select');
            if (window.jQuery &&
                window.jQuery.fn &&
                window.jQuery.fn.select2) {
                window.jQuery(onlySelect).val(null).trigger('change');
            }

            return;
        }

        var row = button.closest('.stn-line-row');
        var product = row.querySelector('.stn-product-select');

        if (window.jQuery &&
            window.jQuery.fn &&
            window.jQuery.fn.select2 &&
            product) {
            window.jQuery(product).select2('destroy');
        }

        row.remove();
        renumberRows();
    });

    document.addEventListener('DOMContentLoaded', function () {
        initialiseProducts(document);

        window.requestAnimationFrame(function () {
            loadLocations().finally(function () {
                // System-wide location auto-selection can occur immediately
                // after the module lookup. Re-read the visible values after
                // the current event queue and twice more as a defensive
                // fallback for legacy global dropdown initialisers.
                window.setTimeout(synchroniseVisibleLocationValues, 0);
                window.setTimeout(synchroniseVisibleLocationValues, 350);
                window.setTimeout(synchroniseVisibleLocationValues, 1200);
            });
        });
    });
})(window, document);
