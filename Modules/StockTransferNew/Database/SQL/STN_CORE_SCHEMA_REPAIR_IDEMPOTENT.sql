  UNIQUE KEY `stnew_stock_transfers_business_transfer_unique` (`business_id`,`transfer_no`),
  KEY `stnew_stock_transfers_business_id_index` (`business_id`),
  KEY `stnew_stock_transfers_status_index` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

