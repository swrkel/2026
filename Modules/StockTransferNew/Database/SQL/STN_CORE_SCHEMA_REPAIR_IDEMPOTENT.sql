  `status` VARCHAR(191) NOT NULL DEFAULT 'draft',
  `approval_mode` VARCHAR(191) NULL,
  `approval_matrix_id` BIGINT UNSIGNED NULL,
  `current_approval_step` INT UNSIGNED NOT NULL DEFAULT 0,
  `reconciliation_status` VARCHAR(191) NULL,
  `reconciliation_resolution` VARCHAR(191) NULL,
  `reconciliation_note` TEXT NULL,
  `reconciled_at` TIMESTAMP NULL,
  `reconciled_by` BIGINT UNSIGNED NULL,
  `reason` TEXT NULL,
  `remarks` TEXT NULL,
  `vehicle_no` VARCHAR(191) NULL,
  `driver_name` VARCHAR(191) NULL,
  `driver_mobile` VARCHAR(191) NULL,
  `approval_note` TEXT NULL,
  `rejection_note` TEXT NULL,
  `cancel_reason` TEXT NULL,
  `created_by` BIGINT UNSIGNED NULL,
  `submitted_by` BIGINT UNSIGNED NULL,
  `approved_by` BIGINT UNSIGNED NULL,
  `returned_by` BIGINT UNSIGNED NULL,
  `rejected_by` BIGINT UNSIGNED NULL,
  `dispatched_by` BIGINT UNSIGNED NULL,
  `received_by` BIGINT UNSIGNED NULL,
  `cancelled_by` BIGINT UNSIGNED NULL,
