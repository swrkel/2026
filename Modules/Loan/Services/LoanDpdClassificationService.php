<?php

namespace Modules\Loan\Services;

use Carbon\Carbon;

use Modules\Loan\Models\LoanApplication;

class LoanDpdClassificationService
{
    /*
    |--------------------------------------------------------------------------
    | Process DPD Buckets
    |--------------------------------------------------------------------------
    */

    public function process()
    {
        /*
        |--------------------------------------------------------------------------
        | Get Active Loans
        |--------------------------------------------------------------------------
        */

        $loans =
            LoanApplication::where(
                'status',
                '!=',
                'closed'
            )->get();

        foreach ($loans as $loan) {

            /*
            |--------------------------------------------------------------------------
            | Skip If No Due Date
            |--------------------------------------------------------------------------
            */

            if (!$loan->next_due_date) {
                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Calculate DPD
            |--------------------------------------------------------------------------
            */

            $dpd =
                Carbon::parse(
                    $loan->next_due_date
                )->diffInDays(
                    now(),
                    false
                );

            /*
            |--------------------------------------------------------------------------
            | Not Yet Due
            |--------------------------------------------------------------------------
            */

            if ($dpd <= 0) {

                $loan->update([

                    'dpd' => 0,

                    'dpd_bucket' =>
                        'current'

                ]);

                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Early Delinquency
            |--------------------------------------------------------------------------
            */

            if ($dpd <= 30) {

                $bucket =
                    '1_30_dpd';
            }

            /*
            |--------------------------------------------------------------------------
            | Moderate Delinquency
            |--------------------------------------------------------------------------
            */

            elseif ($dpd <= 60) {

                $bucket =
                    '31_60_dpd';
            }

            /*
            |--------------------------------------------------------------------------
            | High Delinquency
            |--------------------------------------------------------------------------
            */

            elseif ($dpd <= 90) {

                $bucket =
                    '61_90_dpd';
            }

            /*
            |--------------------------------------------------------------------------
            | Severe Delinquency
            |--------------------------------------------------------------------------
            */

            else {

                $bucket =
                    '90_plus_dpd';
            }

            /*
            |--------------------------------------------------------------------------
            | Update Loan
            |--------------------------------------------------------------------------
            */

            $loan->update([

                'dpd' => $dpd,

                'dpd_bucket' => $bucket,

                'status' => 'overdue'

            ]);
        }
    }
}