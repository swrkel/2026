-- Historical sales had no Per Unit Discount. Preserve those values exactly.
-- Run this backfill ONLY when net_unit_price was created by this import. That
-- keeps the SQL repeatable without damaging a later legitimate 100% unit
-- discount whose net_unit_price is correctly zero.
SET @rcm_v39_sql := IF(
    @rcm_v39_has_net_unit_price = 0,
    'UPDATE `rcm_dispatch_lines` SET `unit_discount_type`=''fixed'', `unit_discount_value`=0, `unit_discount_amount`=0, `net_unit_price`=`unit_price`',
    'SELECT ''v39 historical line backfill already completed'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;
