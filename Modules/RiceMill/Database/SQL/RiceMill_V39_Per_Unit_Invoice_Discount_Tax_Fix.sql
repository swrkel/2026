-- Rice Mill v39 - Per Unit + Per Invoice Discount and Percentage Tax correction
-- Incremental SQL for an EXISTING tenant database.
-- Safe to run repeatedly in phpMyAdmin. No stored procedure is used.
-- Run inside the correct tenant DB only (for example: nivasa_2003).
--
-- IMPORTANT: This v39 SQL is cumulative for the Sales Invoice changes. It also
-- creates the v38 Invoice Discount / Tax % columns when they are still missing,
-- so an existing tenant can move directly from v37 (or earlier) to v39 without
-- separately importing the v38 SQL first.
SET NAMES utf8mb4;

-- v38 cumulative compatibility: Invoice Discount Type.
SET @rcm_v39_had_discount_type := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'rcm_dispatches' AND COLUMN_NAME = 'discount_type'
);
SET @rcm_v39_sql := IF(
    @rcm_v39_had_discount_type = 0,
    'ALTER TABLE `rcm_dispatches` ADD COLUMN `discount_type` VARCHAR(20) NOT NULL DEFAULT ''fixed'' AFTER `subtotal`',
    'SELECT ''rcm_dispatches.discount_type already exists'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;

-- v38 cumulative compatibility: selected Invoice Discount value.
SET @rcm_v39_had_discount_value := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'rcm_dispatches' AND COLUMN_NAME = 'discount_value'
);
SET @rcm_v39_sql := IF(
    @rcm_v39_had_discount_value = 0,
    'ALTER TABLE `rcm_dispatches` ADD COLUMN `discount_value` DECIMAL(20,4) NOT NULL DEFAULT 0 AFTER `discount_type`',
    'SELECT ''rcm_dispatches.discount_value already exists'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;

-- v38 cumulative compatibility: Tax percentage.
SET @rcm_v39_had_tax_percent := (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'rcm_dispatches' AND COLUMN_NAME = 'tax_percent'
);
SET @rcm_v39_sql := IF(
    @rcm_v39_had_tax_percent = 0,
    'ALTER TABLE `rcm_dispatches` ADD COLUMN `tax_percent` DECIMAL(10,4) NOT NULL DEFAULT 0 AFTER `discount_amount`',
    'SELECT ''rcm_dispatches.tax_percent already exists'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;

-- If the v38 fields were just introduced, preserve historical invoice values.
SET @rcm_v39_sql := IF(
    @rcm_v39_had_discount_value = 0,
    'UPDATE `rcm_dispatches` SET `discount_type`=''fixed'', `discount_value`=`discount_amount` WHERE `discount_amount`<>0',
    'SELECT ''v38 historical invoice discount backfill already completed'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;

SET @rcm_v39_sql := IF(
    @rcm_v39_had_tax_percent = 0,
    'UPDATE `rcm_dispatches` SET `tax_percent`=ROUND((`tax_amount` / (`subtotal` - `discount_amount`)) * 100, 4) WHERE `tax_amount`<>0 AND (`subtotal` - `discount_amount`) > 0',
    'SELECT ''v38 historical tax percentage backfill already completed'''
);
PREPARE rcm_v39_stmt FROM @rcm_v39_sql;
EXECUTE rcm_v39_stmt;
DEALLOCATE PREPARE rcm_v39_stmt;

